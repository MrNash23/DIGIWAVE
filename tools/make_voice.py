"""Speaks the announcements with the Piper speech synthesis and converts them
into C arrays: 12 kHz, mono, 16 bit, silence at both ends removed.

The voice is Piper's "ljspeech", trained on the public-domain LJ Speech dataset,
so the clips may be passed on under the licence of DIGIWAVE. Set up once:

    pip install piper-tts
    curl -LO https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_US/ljspeech/high/en_US-ljspeech-high.onnx
    curl -LO https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_US/ljspeech/high/en_US-ljspeech-high.onnx.json

Run from the project root:  python3 tools/make_voice.py path/to/en_US-ljspeech-high.onnx
Writes src/assets/voice.c and src/assets/voice.h.
"""
import math
import os
import struct
import subprocess
import sys
import tempfile
import wave

OUT = "src/assets"
LENGTH_SCALE = 0.95  # Piper's speaking pace; below 1 is faster
SAMPLE_RATE = 12000

# name in the firmware -> what is said; letters are spaced so that they are spelled
PHRASES = [
    ("new_station", "New station calling C Q."),
    ("calling_you", "Station calling you."),
    ("qso_started", "Q S O started."),
    ("qso_logged", "Q S O logged."),
]

SILENCE = 300     # samples below this level count as silence
MARGIN = 240      # 20 ms kept before and after the speech
PEAK = 0.95       # all clips are scaled to the same peak, of full scale
DRIVE = 3.0       # soft compression: the quiet syllables come up, the peaks stay below full scale


def resample(samples, rate_in, rate_out):
    """Windowed-sinc resampling; the cutoff lies below both Nyquist frequencies."""
    ratio = rate_out / rate_in
    cutoff = 0.45 * min(1.0, ratio)
    half = 32
    out = []
    for n in range(int(len(samples) * ratio)):
        t = n / ratio
        centre = int(t)
        acc = 0.0
        for k in range(centre - half + 1, centre + half + 1):
            if 0 <= k < len(samples):
                x = t - k
                sinc = 2 * cutoff if x == 0 else math.sin(2 * math.pi * cutoff * x) / (math.pi * x)
                window = 0.5 + 0.5 * math.cos(math.pi * x / half)
                acc += samples[k] * sinc * window
        out.append(acc)
    return out


def speak(model, text):
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "clip.wav")
        subprocess.run([sys.executable, "-m", "piper", "-m", model, "-f", path,
                        "--length-scale", str(LENGTH_SCALE)], input=text.encode(), check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        with wave.open(path) as w:
            if w.getnchannels() != 1 or w.getsampwidth() != 2:
                raise ValueError(f"unexpected format from piper for {text!r}")
            rate = w.getframerate()
            data = w.readframes(w.getnframes())
    samples = resample(struct.unpack(f"<{len(data) // 2}h", data), rate, SAMPLE_RATE)
    loud = [i for i, s in enumerate(samples) if abs(s) > SILENCE]
    start = max(0, loud[0] - MARGIN)
    end = min(len(samples), loud[-1] + MARGIN)
    samples = samples[start:end]
    # Normalised to 1, then through a tanh curve, which raises the loudness of a small speaker
    norm = 1.0 / max(abs(s) for s in samples)
    scale = PEAK * 32767 / math.tanh(DRIVE)
    return [max(-32768, min(32767, round(math.tanh(DRIVE * s * norm) * scale))) for s in samples]


def main():
    if not os.path.isdir(OUT):
        sys.exit("run from the project root")
    if len(sys.argv) != 2:
        sys.exit("usage: python3 tools/make_voice.py path/to/en_US-ljspeech-high.onnx")
    model = sys.argv[1]
    notice = ["// SPDX-License-Identifier: GPL-3.0-or-later", "// Copyright (C) 2026 Andres Leroi",
              "// Generated by tools/make_voice.py - do not edit."]
    header = notice + ["#pragma once", "", "#include <stddef.h>", "#include <stdint.h>", "", "#ifdef __cplusplus",
                       'extern "C" {', "#endif", "", f"#define VOICE_SAMPLE_RATE {SAMPLE_RATE}", ""]
    source = notice + ["", '#include "voice.h"', ""]
    for name, text in PHRASES:
        samples = speak(model, text)
        header.append(f"extern const int16_t voice_{name}[];  // \"{text}\", {len(samples) / SAMPLE_RATE:.2f} s")
        header.append(f"extern const size_t voice_{name}_len;")
        source.append(f"const int16_t voice_{name}[] = {{")
        for i in range(0, len(samples), 16):
            source.append("    " + ", ".join(str(s) for s in samples[i:i + 16]) + ",")
        source.append("};")
        source.append(f"const size_t voice_{name}_len = {len(samples)};")
        source.append("")
        print(f"{name}: {len(samples) / SAMPLE_RATE:.2f} s")
    header += ["", "#ifdef __cplusplus", "}", "#endif"]
    with open(os.path.join(OUT, "voice.h"), "w") as f:
        f.write("\n".join(header) + "\n")
    with open(os.path.join(OUT, "voice.c"), "w") as f:
        f.write("\n".join(source))


if __name__ == "__main__":
    main()
